/// What the system will let this device do about making a direct link, and how
/// to ask it.
///
/// None of it is something the shared UI can do by itself: turning a phone into
/// a hotspot or opening the tethering settings is platform code, and on the
/// desktop there is no equivalent at all. So the apps supply an implementation
/// (Android does, Linux passes nothing) and the screen adapts to what it gets -
/// which is the same shape as [SynchronizerApp.prepareNetwork].
///
/// Everything here is best-effort by nature: a hotspot can be refused by the
/// user, by a missing permission, or by an OEM that never implemented it. The
/// screen has to keep working when all of it says no, because typing an address
/// by hand always works and is the fallback all of this is decorating.
abstract interface class PlatformNetwork {
  /// Points this app's sockets at the local network, so a VPN does not carry
  /// them off somewhere the other device is not.
  ///
  /// Returns what it bound to ("wifi", "ethernet") or null if there was nothing
  /// to bind to - which includes the ordinary case of no VPN being in the way.
  /// Only this app is affected; every other app keeps using the tunnel.
  Future<String?> bindToLocalNetwork();

  /// Gives the app's traffic back to the system's routing.
  Future<void> releaseNetwork();

  /// Whether a VPN is carrying this device's traffic right now.
  Future<bool> vpnActive();

  /// Whether this device can be asked to host a hotspot at all. False on a
  /// platform with no such API, so the offer is not made in the first place.
  Future<bool> canHostHotspot();

  /// Turns this device into a hotspot the other one can join, and returns the
  /// credentials to read out. Null if it could not be started - refused,
  /// unsupported, or the user said no to the permission it needs.
  ///
  /// The hotspot is local-only: it carries no internet, which is exactly what
  /// is wanted here and also why the system allows an app to ask for it.
  Future<HotspotCredentials?> startHotspot();

  /// Takes the hotspot down. Safe to call when none is running.
  Future<void> stopHotspot();

  /// Opens the system screen for USB and Wi-Fi tethering. False if there is no
  /// such screen to open, in which case the user has to be told where to go.
  Future<bool> openTetheringSettings();

  /// Opens the system Wi-Fi picker, for joining the hotspot the other device is
  /// hosting. False if there is none to open.
  Future<bool> openWifiSettings();

  /// Joins the network named in a scanned QR code and routes this app's
  /// traffic over it. False if the platform cannot, the user declined the
  /// system's prompt, or nothing answered to that name.
  ///
  /// Android will not silently join a network on an app's say-so - and should
  /// not - so this shows the system's own "connect to this network?" sheet. It
  /// binds only this app: the user's saved networks are untouched and their
  /// normal connection comes back when [leaveWifi] runs.
  Future<bool> joinWifi(String ssid, String passphrase);

  /// Gives up the network joined by [joinWifi] and puts this app's traffic back
  /// where it was.
  Future<void> leaveWifi();
}

/// The old name, kept so the direct screen reads as it did: what the platform
/// can do about making a link is part of what it can do about networking.
typedef DirectLinkControls = PlatformNetwork;

/// The name and password of a hotspot this device is hosting. Generated by the
/// system, not chosen by the app, and only good until the hotspot stops.
class HotspotCredentials {
  const HotspotCredentials({required this.ssid, required this.passphrase});

  final String ssid;
  final String passphrase;
}
